export const WELCOME_BODIES = { 'pt-BR': pt, en }

export function welcomeBody(language = 'pt-BR') {
  return WELCOME_BODIES[language] ?? WELCOME_BODIES['pt-BR']
}

/** The help page as a new note, for the "recreate help page" command. */
export function welcomeNote(language) {
  return { name: WELCOME_NAME, body: welcomeBody(language) }
}
